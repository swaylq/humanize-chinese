#!/usr/bin/env python3
"""Punctuation normalisation for cross-corpus comparison.

Why this exists: the CSL / NLPCC corpora on disk were normalised to halfwidth
ASCII commas between Chinese characters ("本研究聚焦于A,通过B..."), while text
freshly generated by a chat model uses fullwidth 「，」. The detector counts
comma density, clause length and punctuation variety, so comparing a halfwidth
corpus against a fullwidth one measures the corpus pipeline rather than the
writing. Every group must pass through here before scoring.

Only punctuation sitting between CJK characters is converted — ASCII inside
numbers ("0.6%", "1,200") and inside Latin runs is left alone.
"""
from __future__ import annotations

import re

CJK = r"一-鿿㐀-䶿"

# halfwidth -> fullwidth, applied only when flanked by CJK
_PAIRS = [
    (",", "，"),
    (";", "；"),
    (":", "："),
    ("!", "！"),
    ("?", "？"),
]

_RULES = [
    (re.compile(rf"(?<=[{CJK}]){re.escape(a)}(?=[{CJK}])"), b)
    for a, b in _PAIRS
]

# A halfwidth period between CJK chars is a sentence end, not a decimal point.
_PERIOD = re.compile(rf"(?<=[{CJK}])\.(?=[{CJK}])")

# Trailing punctuation at end of a CJK line.
_TAIL = [
    (re.compile(rf"(?<=[{CJK}]),\s*$", re.M), "，"),
    (re.compile(rf"(?<=[{CJK}])\.\s*$", re.M), "。"),
]

_SPACE_AROUND_FW = re.compile(r"\s+(?=[，。；：！？、」』）])")


def normalize_punct(text: str) -> str:
    """Return text with CJK-internal halfwidth punctuation made fullwidth."""
    s = text.replace("\r\n", "\n").replace("\r", "\n")
    for pat, rep in _RULES:
        s = pat.sub(rep, s)
    s = _PERIOD.sub("。", s)
    for pat, rep in _TAIL:
        s = pat.sub(rep, s)
    s = _SPACE_AROUND_FW.sub("", s)
    # collapse runs of blank lines to a single paragraph break
    while "\n\n\n" in s:
        s = s.replace("\n\n\n", "\n\n")
    return s.strip()


def count_cn(text: str) -> int:
    return sum(1 for ch in text if "一" <= ch <= "鿿")


def punct_profile(text: str) -> dict:
    """Diagnostic: which comma form dominates. Used to prove normalisation ran."""
    return {
        "halfwidth_comma": text.count(","),
        "fullwidth_comma": text.count("，"),
        "halfwidth_period": len(re.findall(rf"(?<=[{CJK}])\.", text)),
        "fullwidth_period": text.count("。"),
        "cn_chars": count_cn(text),
    }


if __name__ == "__main__":
    import sys
    src = sys.stdin.read()
    print("before:", punct_profile(src), file=sys.stderr)
    out = normalize_punct(src)
    print("after: ", punct_profile(out), file=sys.stderr)
    sys.stdout.write(out)
